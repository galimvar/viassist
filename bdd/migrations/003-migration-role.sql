-- 003-migration-role.sql : aligner la base sur le MLD v1
--   * les ENUM "role" et "rdv_categorie" deviennent des tables de référence
--   * personne.role  -> personne.role_id (FK vers role)
--   * evenement.type -> evenement.type_evenement_id (FK vers type_evenement)
--   * nom -> intitule (evenement, categorie), unicité du mail et de categorie.intitule
--   * champs facultatifs : evenement.description, message.categorie_id
--
-- Tout est dans une transaction : si une étape échoue, rien n'est modifié.
-- Les données existantes sont conservées (les valeurs d'ENUM sont recopiées
-- dans les nouvelles tables, puis les lignes sont rattachées).

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. ROLE : de l'ENUM à la table
-- ---------------------------------------------------------------------------
-- Une table et un type partagent le même espace de noms dans Postgres :
-- on libère d'abord le nom "role" en renommant l'ancien type.
ALTER TYPE "role" RENAME TO "role_ancien";

CREATE TABLE "role" (
	"id" INTEGER NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"intitule" VARCHAR(50) NOT NULL UNIQUE,
	PRIMARY KEY("id")
);

-- Recopie des valeurs de l'ENUM, dans leur ordre de déclaration
INSERT INTO "role" ("intitule")
SELECT unnest(enum_range(NULL::"role_ancien"))::text;

ALTER TABLE "personne" ADD COLUMN "role_id" INTEGER;

UPDATE "personne" p
SET "role_id" = r."id"
FROM "role" r
WHERE r."intitule" = p."role"::text;

ALTER TABLE "personne" ALTER COLUMN "role_id" SET NOT NULL;
ALTER TABLE "personne"
ADD FOREIGN KEY("role_id") REFERENCES "role"("id")
ON UPDATE NO ACTION ON DELETE NO ACTION;

ALTER TABLE "personne" DROP COLUMN "role";
DROP TYPE "role_ancien";

-- ---------------------------------------------------------------------------
-- 2. TYPE_EVENEMENT : de l'ENUM rdv_categorie à la table
-- ---------------------------------------------------------------------------
CREATE TABLE "type_evenement" (
	"id" INTEGER NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"intitule" VARCHAR(50) NOT NULL UNIQUE,
	PRIMARY KEY("id")
);

INSERT INTO "type_evenement" ("intitule")
SELECT unnest(enum_range(NULL::"rdv_categorie"))::text;

ALTER TABLE "evenement" ADD COLUMN "type_evenement_id" INTEGER;

UPDATE "evenement" e
SET "type_evenement_id" = t."id"
FROM "type_evenement" t
WHERE t."intitule" = e."type"::text;

ALTER TABLE "evenement" ALTER COLUMN "type_evenement_id" SET NOT NULL;
ALTER TABLE "evenement"
ADD FOREIGN KEY("type_evenement_id") REFERENCES "type_evenement"("id")
ON UPDATE NO ACTION ON DELETE NO ACTION;

ALTER TABLE "evenement" DROP COLUMN "type";
DROP TYPE "rdv_categorie";

-- ---------------------------------------------------------------------------
-- 3. Renommages et contraintes du MLD
-- ---------------------------------------------------------------------------
ALTER TABLE "evenement" RENAME COLUMN "nom" TO "intitule";
ALTER TABLE "evenement" ALTER COLUMN "description" DROP NOT NULL;   -- facultatif

ALTER TABLE "categorie" RENAME COLUMN "nom" TO "intitule";
ALTER TABLE "categorie" ADD CONSTRAINT "categorie_intitule_key" UNIQUE ("intitule");

ALTER TABLE "message" ALTER COLUMN "categorie_id" DROP NOT NULL;    -- facultatif

-- Un mail = un seul compte (le service d'inscription compte sur l'erreur 23505)
-- Échoue s'il existe déjà des doublons : à nettoyer avant de relancer.
ALTER TABLE "personne" ADD CONSTRAINT "personne_mail_key" UNIQUE ("mail");

-- ---------------------------------------------------------------------------
-- 4. Index sur les clés étrangères (Postgres n'en crée pas automatiquement)
-- ---------------------------------------------------------------------------
CREATE INDEX "idx_personne_role_id" ON "personne"("role_id");
CREATE INDEX "idx_evenement_personne_id" ON "evenement"("personne_id");
CREATE INDEX "idx_evenement_type_evenement_id" ON "evenement"("type_evenement_id");
CREATE INDEX "idx_evenement_date_debut" ON "evenement"("date_debut");
CREATE INDEX "idx_participer_evenement_id" ON "participer"("evenement_id");
CREATE INDEX "idx_message_personne_id" ON "message"("personne_id");
CREATE INDEX "idx_message_categorie_id" ON "message"("categorie_id");
CREATE INDEX "idx_message_date" ON "message"("date");

COMMIT;