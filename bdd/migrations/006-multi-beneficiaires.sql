-- 006-multi-beneficiaires.sql : plusieurs bénéficiaires, rôle porté par le lien (cf. ADR 006)
--   * nouvelle table beneficiaire (compte facultatif via personne_id)
--   * nouvelle table accompagner (personne, bénéficiaire, rôle, statut de l'invitation)
--   * evenement.beneficiaire_id et message.beneficiaire_id (obligatoires)
--   * personne.role_id est supprimé : le rôle dépend du bénéficiaire
--
-- Tout est dans une transaction : si une étape échoue, rien n'est modifié.
-- Les données existantes sont rattachées à un bénéficiaire (étape 3).
--
-- PRÉREQUIS sur une base qui contient déjà des événements ou des messages : au moins une
-- personne avec role_id = 5 (bénéficiaire), qui devient le bénéficiaire de reprise. Sinon,
-- l'étape 4 échoue avec « column "beneficiaire_id" … contains null values » et la transaction
-- annule tout : créer ou corriger cette personne, puis relancer. Sur une base vide, rien à faire.

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Nouvelles tables
-- ---------------------------------------------------------------------------
CREATE TABLE "beneficiaire" (
	"id" INTEGER NOT NULL UNIQUE GENERATED BY DEFAULT AS IDENTITY,
	"nom" VARCHAR(50) NOT NULL,
	"prenom" VARCHAR(50) NOT NULL,
	"date_naissance" DATE,
	-- Compte du bénéficiaire s'il en a un. UNIQUE : un compte = au plus un bénéficiaire
	"personne_id" INTEGER UNIQUE REFERENCES "personne"("id")
		ON UPDATE NO ACTION ON DELETE SET NULL,
	"est_archive" BOOLEAN NOT NULL DEFAULT FALSE,
	PRIMARY KEY("id")
);

CREATE TABLE "accompagner" (
	"personne_id" INTEGER NOT NULL REFERENCES "personne"("id")
		ON UPDATE NO ACTION ON DELETE CASCADE,
	"beneficiaire_id" INTEGER NOT NULL REFERENCES "beneficiaire"("id")
		ON UPDATE NO ACTION ON DELETE CASCADE,
	"role_id" INTEGER NOT NULL REFERENCES "role"("id")
		ON UPDATE NO ACTION ON DELETE NO ACTION,
	-- 'en_attente' : invitation envoyée par un admin, AUCUN accès tant qu'elle n'est pas acceptée.
	-- DEFAULT 'accepte' : les liens repris à l'étape 3 (et ceux du seed) sont déjà acceptés.
	"statut" VARCHAR(20) NOT NULL DEFAULT 'accepte'
		CHECK ("statut" IN ('en_attente', 'accepte')),
	PRIMARY KEY("personne_id", "beneficiaire_id")
);

-- ---------------------------------------------------------------------------
-- 2. Rattachement des événements et messages (NULL le temps de la reprise)
-- ---------------------------------------------------------------------------
ALTER TABLE "evenement" ADD COLUMN "beneficiaire_id" INTEGER;
ALTER TABLE "message" ADD COLUMN "beneficiaire_id" INTEGER;

-- ---------------------------------------------------------------------------
-- 3. Reprise des données existantes
-- ---------------------------------------------------------------------------

INSERT INTO "beneficiaire" ("nom", "prenom", "date_naissance", "personne_id")
SELECT "nom", "prenom", "date_naissance", "id"
FROM "personne"
WHERE role_id = 5;


-- V1 : un seul bénéficiaire attendu. S'il y en a plusieurs, tout est rattaché au plus ancien.
UPDATE "evenement"
SET "beneficiaire_id" = (SELECT id FROM beneficiaire ORDER BY id LIMIT 1);

-- V1 : un seul bénéficiaire attendu. S'il y en a plusieurs, tout est rattaché au plus ancien.
UPDATE "message"
SET "beneficiaire_id" = (SELECT id FROM beneficiaire ORDER BY id LIMIT 1);

INSERT INTO "accompagner" ("personne_id", "beneficiaire_id", "role_id")
SELECT p.id, b.id, p.role_id
FROM "personne" p
CROSS JOIN "beneficiaire" b;

-- ---------------------------------------------------------------------------
-- 4. Contraintes définitives
-- ---------------------------------------------------------------------------
-- Échoue si l'étape 3 a laissé des événements ou des messages sans bénéficiaire.
ALTER TABLE "evenement" ALTER COLUMN "beneficiaire_id" SET NOT NULL;
ALTER TABLE "evenement"
ADD FOREIGN KEY("beneficiaire_id") REFERENCES "beneficiaire"("id")
ON UPDATE NO ACTION ON DELETE NO ACTION;

ALTER TABLE "message" ALTER COLUMN "beneficiaire_id" SET NOT NULL;
ALTER TABLE "message"
ADD FOREIGN KEY("beneficiaire_id") REFERENCES "beneficiaire"("id")
ON UPDATE NO ACTION ON DELETE NO ACTION;

-- Le rôle n'est plus global (l'index idx_personne_role_id part avec la colonne)
ALTER TABLE "personne" DROP COLUMN "role_id";

-- ---------------------------------------------------------------------------
-- 5. Index sur les clés étrangères
-- ---------------------------------------------------------------------------
-- accompagner(personne_id, ...) est déjà couvert par la clé primaire
CREATE INDEX "idx_accompagner_beneficiaire_id" ON "accompagner"("beneficiaire_id");
CREATE INDEX "idx_evenement_beneficiaire_id" ON "evenement"("beneficiaire_id");
CREATE INDEX "idx_message_beneficiaire_id" ON "message"("beneficiaire_id");

COMMIT;
